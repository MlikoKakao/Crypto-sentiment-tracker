def language_from_browser_locale(locale: str | None) -> str:
    """Map a browser locale to one of the languages supported by the app."""
    normalized = (locale or "").lower()
    traditional_chinese_locales = ("zh-tw", "zh-hant", "zh-hk", "zh-mo")
    if normalized.startswith(traditional_chinese_locales):
        return "zh-TW"
    return "en"
